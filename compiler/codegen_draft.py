"""codegen_draft.py — DRAFT stage-7 code generation for the full ct_mul (L3 / int8).

Walks a scheduled L3 Program and emits a device DISPATCH PLAN: a DRAM buffer per Value, each op
mapped to its device kernel (kernels/ir/*), placed on a core, grouped into dependency WAVES.
Two artifacts: a machine-readable JSON plan, and a readable C++-ish dispatch sketch. This is a DRAFT
— it does not compile against tt-metalium; it shows the structure a real emitter would produce
(kernel selection, buffer/Value binding, per-wave per-core dispatch, memory-tier handoffs from the
schedule's Fusion-B classification). Extends codegen.py (which handled the pointwise subset).

Run:  python3 codegen_draft.py     # writes ctmul_dispatch.{json,cpp.txt}
"""
from __future__ import annotations
import os, sys, json

import _paths                                     # noqa: F401  (repo layout; see _paths.py)
from ir import outputs                                       # noqa: E402

# opcode -> (kernel symbol, kernels/ir source hint). Structural ops become buffer views / NoC.
KERNEL = {
    "tile.matmul_modq":     ("matmul_modq",   "compute/matmul_modq.cpp"),
    "tile.matmul_wide":     ("matmul_wide",   "compute/matmul_modq.cpp (no final reduce)"),
    "tile.mul_modq":        ("mul_modq",      "compute/mul_modq.cpp"),
    "tile.add_modq":        ("add_modq",      "compute/add_modq.cpp"),
    "tile.sub_modq":        ("sub_modq",      "compute/sub_modq.cpp"),
    "tile.decompose":       ("decompose",     "compute/gadget_decompose.cpp"),
    "tile.recombine_modq":  ("recombine_modq", "compute/recombine_rns.cpp"),
    "tile.recombine_wide":  ("recombine_wide", "compute/recombine_rns.cpp (place-value, no reduce)"),
    "tile.fixed_slice":     ("fixed_slice",   "compute/eps_correct_crns.cpp (shift/mask)"),
    "tile.transpose":       ("transpose",     "compute/transpose.cpp"),
    "tile.const":           ("const_load",    "reader (baked constant -> DRAM)"),
    "rns.const":            ("const_load",    "reader (baked constant -> DRAM)"),
}
STRUCTURAL = {"tile.reshape", "tile.slice", "tile.concat", "tile.split", "tile.all_to_all_tiles"}


def plan(prog, sch):
    """Build a dispatch plan dict: buffers, ops (kernel/core/wave/io), waves, stats."""
    ops = prog.ops
    prod_of = {}
    for i, op in enumerate(ops):
        for v in outputs(op):
            prod_of[v.name] = i

    # buffers: one per Value (inputs, op results). size in tiles.
    bufs, border = {}, []
    def buf(v):
        if v.name not in bufs:
            shp = tuple(v.shape) or (1,)
            tiles = max(1, (1 if len(shp) < 2 else shp[0]) * (shp[-1]) // 1024) if False else max(1, int(1))
            bufs[v.name] = {"id": len(border), "shape": list(shp), "dtype": v.dtype,
                            "q": (str(v.q) if v.q is not None else None)}
            border.append(v.name)
        return bufs[v.name]["id"]
    for v in prog.inputs:
        buf(v)

    # dependency waves (levels): wave[i] = 1 + max(wave[dep])
    dep = [[prod_of[o.name] for o in op.operands if o.name in prod_of] for op in ops]
    wave = [0] * len(ops)
    for i, op in enumerate(ops):
        wave[i] = 1 + max((wave[d] for d in dep[i]), default=-1)

    core = sch.get("core", [0] * len(ops)) if sch else [0] * len(ops)
    edge_tier = {}
    for (d, i, t) in (sch.get("edges", []) if sch else []):
        edge_tier[(d, i)] = t

    plan_ops = []
    for i, op in enumerate(ops):
        outs = outputs(op)
        for v in outs:
            buf(v)
        if op.opcode in STRUCTURAL:
            kern, src = ("relayout" if op.opcode == "tile.all_to_all_tiles" else "view"), "(buffer view / NoC)"
        else:
            kern, src = KERNEL.get(op.opcode, (op.opcode, "?"))
        plan_ops.append({
            "idx": i, "wave": wave[i], "core": core[i] if i < len(core) else 0,
            "kernel": kern, "src": src, "opcode": op.opcode,
            "in": [buf(o) for o in op.operands],
            "out": [bufs[v.name]["id"] for v in outs],
            "handoffs": [edge_tier.get((prod_of[o.name], i), "sram")
                         for o in op.operands if o.name in prod_of],
        })
    nwaves = (max(wave) + 1) if ops else 0
    from collections import Counter
    kern_hist = Counter(p["kernel"] for p in plan_ops if p["kernel"] not in ("view",))
    return {"buffers": bufs, "n_buffers": len(border), "ops": plan_ops, "n_ops": len(ops),
            "n_waves": nwaves, "kernel_histogram": dict(kern_hist)}


def emit_cpp(pl) -> str:
    """A readable C++-ish dispatch sketch (one program per wave; kernels placed per core)."""
    L = ["// DRAFT device dispatch for ct_mul (L3/int8) — generated by codegen_draft.py",
         "// NOT tt-metalium-compilable; shows kernel selection + buffer binding + waves.",
         f"// {pl['n_ops']} ops, {pl['n_buffers']} DRAM buffers, {pl['n_waves']} dependency waves.", "",
         "void ct_mul_dispatch(Device& dev) {"]
    L.append(f"  // --- allocate {pl['n_buffers']} DRAM buffers (one per SSA Value) ---")
    L.append("  auto B = alloc_dram(/*count=*/%d);" % pl["n_buffers"])
    by_wave = {}
    for p in pl["ops"]:
        by_wave.setdefault(p["wave"], []).append(p)
    for w in sorted(by_wave):
        wave_ops = by_wave[w]
        cores = sorted({p["core"] for p in wave_ops})
        L.append(f"\n  // ===== wave {w}  ({len(wave_ops)} ops on {len(cores)} cores) =====")
        L.append(f"  Program prog{w}; // one dispatch; independent ops run concurrently across cores")
        for p in wave_ops[:400]:                             # cap the sketch
            ins = ", ".join(f"B[{b}]" for b in p["in"])
            outs = ", ".join(f"B[{b}]" for b in p["out"])
            if p["kernel"] == "view":
                L.append(f"    /* {p['opcode']} -> {outs} : buffer view (no kernel) */")
            else:
                ht = "".join("*" if h == "noc" else "." for h in p["handoffs"])  # . SRAM  * NoC hop
                L.append(f"    core[{p['core']:>2}].enqueue(\"{p['kernel']}\", {{{ins}}} -> {{{outs}}});"
                         f"  // handoffs[{ht}]")
        if len(wave_ops) > 400:
            L.append(f"    // ... {len(wave_ops)-400} more ops in this wave")
        L.append(f"  dev.run(prog{w});")
    L.append("}")
    return "\n".join(L)


if __name__ == "__main__":
    import random
    from bfv_mul_ref import MulParams, encrypt                # noqa: E402
    from bfv_relin_ref import small_poly, keygen_relin        # noqa: E402
    from builders import build_ct_mul_rns                     # noqa: E402
    from lower import lower_l1_to_l2, lower_l2_to_l3, fuse_a   # noqa: E402
    import schedule as sched                                  # noqa: E402

    pp = MulParams(N=16, LQ=3, LP=3, LB=4)
    rng = random.Random(4); s = small_poly(pp.N, rng); e0, e1 = keygen_relin(pp, s, rng)
    ctA = encrypt(pp, [rng.randrange(pp.t) for _ in range(pp.N)], s, rng)
    ctB = encrypt(pp, [rng.randrange(pp.t) for _ in range(pp.N)], s, rng)
    prog, _, _, _ = build_ct_mul_rns(pp, ctA, ctB, e0, e1)
    l3 = lower_l2_to_l3(fuse_a(lower_l1_to_l2(prog)))
    sc = sched.schedule(l3, 8)
    pl = plan(l3, sc)
    outdir = os.path.dirname(__file__)
    with open(os.path.join(outdir, "ctmul_dispatch.json"), "w") as f:
        json.dump({k: v for k, v in pl.items() if k != "buffers"}, f, indent=1)
    with open(os.path.join(outdir, "ctmul_dispatch.cpp.txt"), "w") as f:
        f.write(emit_cpp(pl) + "\n")
    print("codegen DRAFT — ct_mul L3 dispatch plan:")
    print(f"  {pl['n_ops']} ops, {pl['n_buffers']} buffers, {pl['n_waves']} waves")
    print(f"  kernels: {pl['kernel_histogram']}")
    print("  wrote ctmul_dispatch.json + ctmul_dispatch.cpp.txt")
