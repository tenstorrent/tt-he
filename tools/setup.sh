# setup.sh — one command to make this repo buildable on a new machine.
#
#   sh tools/setup.sh
#
# Searches for an installed tt-metalium prefix, then WRITES config.local.env with what it found.
# When it cannot find one, it says exactly what to do -- including the common case of having a
# tt-metal build tree instead of an install. Re-runnable; never overwrites without saying so.
set -u   # NB: no `pipefail` -- these scripts must run under POSIX sh (dash)

REPO="$(cd "$(dirname "$0")/.." && pwd)"
LOCAL="$REPO/config.local.env"

usable() { [ -n "${1:-}" ] && [ -f "$1/lib/cmake/tt-metalium/tt-metalium-config.cmake" ] && [ -d "$1/libexec/tt-metalium" ]; }

echo "== searching for an installed tt-metalium prefix =="
FOUND=""
for c in "${TT_METALIUM_PREFIX:-}" /usr/local "$HOME/work/ttm-install" "$REPO/../ttm-install"; do
    [ -z "$c" ] && continue
    if usable "$c"; then FOUND="$(cd "$c" && pwd)"; echo "  found: $FOUND"; break; fi
    [ -d "$c" ] && echo "  not usable: $c (missing CMake package files and/or libexec/tt-metalium)"
done

if [ -z "$FOUND" ]; then
    echo
    echo "No installed tt-metalium found. This repo needs an INSTALL prefix, not a build tree."
    for b in "$HOME/work/tt-metal" "$REPO/../tt-metal"; do
        if [ -f "$b/build_Release/CMakeCache.txt" ] || [ -f "$b/build/CMakeCache.txt" ]; then
            echo
            echo "  You appear to have a tt-metal source build at: $b"
            echo "  Turn it into an install prefix with:"
            echo "      sh tools/install_ttmetalium.sh -s $b"
            echo "  then re-run: sh tools/setup.sh"
            exit 1
        fi
    done
    echo
    echo "  If tt-metal is installed somewhere unusual, set it by hand:"
    echo "      echo 'TT_METALIUM_PREFIX=/path/to/prefix' >> config.local.env"
    echo "  A valid prefix contains BOTH:"
    echo "      host/lib/cmake/tt-metalium/tt-metalium-config.cmake"
    echo "      libexec/tt-metalium/"
    exit 1
fi

VER=""
VERFILE="$FOUND/lib/cmake/tt-metalium/tt-metalium-config-version.cmake"
[ -f "$VERFILE" ] && VER=$(grep -oE 'set\(PACKAGE_VERSION "[^"]+"' "$VERFILE" | grep -oE '[0-9.]+')
[ -n "$VER" ] && echo "  version: $VER"

echo
if [ -f "$LOCAL" ]; then
    echo "== config.local.env already exists; leaving it alone =="
    echo "  current contents:"; sed 's/^/    /' "$LOCAL"
    echo "  (delete it and re-run to regenerate)"
else
    echo "== writing config.local.env =="
    {
        echo "# config.local.env -- machine-specific, gitignored. Generated by tools/setup.sh."
        echo "# Keys and their meaning are documented in config.defaults.env."
        echo "TT_METALIUM_PREFIX=$FOUND"
    } > "$LOCAL"
    sed 's/^/    /' "$LOCAL"
fi

echo
echo "== verifying =="
sh "$REPO/tools/doctor.sh"
rc=$?
echo
if [ "$rc" = "0" ]; then
    echo "Next:  . env.sh && cd device && cmake -B build -G Ninja && cmake --build build -j"
fi
exit $rc
