# env.sh — single source of truth for the tt-metalium environment.  POSIX sh; source it:
#     . "$REPO_ROOT/env.sh"
#
# Every build/run entry point in this repo (tools/bench/hemul_cross.sh, compiler/run.sh,
# and any manual `cmake -B build`) goes through here, so a new machine needs exactly
# one thing set -- the install prefix -- instead of four variables in N scripts.
#
# WHERE THE VALUES COME FROM (first wins):
#     1. the environment      TT_METALIUM_PREFIX=... ./something
#     2. config.local.env     per-machine, gitignored  (written by `sh tools/setup.sh`)
#     3. config.defaults.env  committed defaults, documents every key
#     4. autodetect           /usr/local, $HOME/work/ttm-install, <repo>/../ttm-install
#
# tt-metalium is consumed as an INSTALL PREFIX, never a build tree: Metalium.cmake and
# tt-logger-targets.cmake are generated by `cmake --install`, so find_package fails against
# .../build_Release.  A prefix P is usable when it has BOTH:
#     P/lib/cmake/tt-metalium/tt-metalium-config.cmake   (for find_package)
#     P/libexec/tt-metalium                              (TT_METAL_HOME: kernels, sfpi, firmware)
# To create one from a build tree, see tools/install_ttmetalium.sh.

_ttm_usable() {
    [ -n "${1:-}" ] && [ -f "$1/lib/cmake/tt-metalium/tt-metalium-config.cmake" ] &&
        [ -d "$1/libexec/tt-metalium" ]
}

# Repo root = directory holding this file. Works when sourced from any cwd, incl. `sh script.sh`.
_ttm_root=$(cd "$(dirname "${TTM_ENV_SELF:-$0}")" 2>/dev/null && pwd)
if [ ! -f "$_ttm_root/env.sh" ]; then
    # Sourced with $0 pointing at the *caller* (normal case): try the known callers' depths.
    for _c in "$_ttm_root" "$_ttm_root/.." "$_ttm_root/../.." "$_ttm_root/../../.."; do
        if [ -f "$_c/env.sh" ]; then _ttm_root=$(cd "$_c" && pwd); break; fi
    done
fi

# Read one key from the config files without eval: local overrides defaults; the environment,
# checked by the caller below, overrides both. Values are taken verbatim (no shell expansion).
_ttm_cfg() {
    for _f in "$_ttm_root/config.local.env" "$_ttm_root/config.defaults.env"; do
        [ -f "$_f" ] || continue
        _v=$(sed -n "s/^[ 	]*$1=//p" "$_f" | sed -e 's/[ 	]*$//' | head -1)
        if [ -n "${_v:-}" ]; then printf '%s' "$_v"; unset _f _v; return 0; fi
    done
    unset _f _v; return 1
}

# NOTE: every expansion here is ${VAR:-}-guarded — callers run with `set -u`.
_ttm_want="${TT_METALIUM_PREFIX:-}"                      # 1. environment
[ -n "$_ttm_want" ] || _ttm_want=$(_ttm_cfg TT_METALIUM_PREFIX)   # 2./3. config files

TT_METALIUM_PREFIX_RESOLVED=""
if [ -n "${_ttm_want:-}" ]; then
    # Explicitly configured: use it or fail loudly. Do NOT silently fall back to something else --
    # a silent fallback is how you end up building against an SDK you did not choose.
    if _ttm_usable "$_ttm_want"; then
        TT_METALIUM_PREFIX_RESOLVED=$(cd "$_ttm_want" && pwd)
    else
        echo "env.sh: configured TT_METALIUM_PREFIX is not a usable install: $_ttm_want" >&2
        if [ -f "$_ttm_want/CMakeCache.txt" ]; then
            echo "  that is a tt-metal BUILD TREE, not an install -- find_package can never use it." >&2
        fi
        echo "  a prefix needs host/lib/cmake/tt-metalium/tt-metalium-config.cmake AND libexec/tt-metalium" >&2
        echo "  run:  sh $_ttm_root/tools/doctor.sh" >&2
        unset _ttm_root _ttm_want _c
        return 1 2>/dev/null || exit 1
    fi
else
    for _p in /usr/local "$HOME/work/ttm-install" "$_ttm_root/../ttm-install"; do   # 4. autodetect
        if _ttm_usable "$_p"; then TT_METALIUM_PREFIX_RESOLVED=$(cd "$_p" && pwd); break; fi
    done
fi

if [ -z "$TT_METALIUM_PREFIX_RESOLVED" ]; then
    echo "env.sh: no usable tt-metalium install found." >&2
    echo "  looked in: \$TT_METALIUM_PREFIX, config.local.env, config.defaults.env," >&2
    echo "             /usr/local, \$HOME/work/ttm-install, $_ttm_root/../ttm-install" >&2
    echo "  fix it with:  sh $_ttm_root/tools/setup.sh      (detects and writes config.local.env)" >&2
    echo "  or diagnose:  sh $_ttm_root/tools/doctor.sh" >&2
    unset _ttm_root _ttm_want _p _c
    return 1 2>/dev/null || exit 1
fi

export TT_METAL_HOME="$TT_METALIUM_PREFIX_RESOLVED/libexec/tt-metalium"
export TT_METAL_RUNTIME_ROOT="$TT_METAL_HOME"
export CMAKE_PREFIX_PATH="$TT_METALIUM_PREFIX_RESOLVED${CMAKE_PREFIX_PATH:+:$CMAKE_PREFIX_PATH}"
# LD_LIBRARY_PATH is belt-and-braces: CMake bakes a RUNPATH into each binary, so the loader already
# finds libtt_metal.so without it. TT_METAL_HOME above is the variable that binaries genuinely need
# at runtime (kernels are JIT-compiled then, using the sfpi compiler inside libexec/tt-metalium).
export LD_LIBRARY_PATH="$TT_METALIUM_PREFIX_RESOLVED/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"

[ -n "${TTM_ENV_QUIET:-}" ] || echo "tt-metalium: $TT_METALIUM_PREFIX_RESOLVED"

unset _ttm_root _ttm_want _p _c
