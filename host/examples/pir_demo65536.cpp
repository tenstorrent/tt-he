// ---- --serve support ---------------------------------------------------------------------------
// One long-lived process owns the device; a UI connects over a Unix socket and gets JSON Lines back.
// The cold pass is per PROCESS (Q=1 ~4.3 s, Q=5 ~579 s), so the daemon must outlive the frontend --
// that is the whole reason this mode exists rather than spawning the binary per request.
namespace serve {

volatile std::sig_atomic_t g_stop = 0;
// Set by the socket loop while a request is in flight; answer() calls it as each stage completes so the
// browser can fill its bars live instead of waiting for the final result.
inline std::function<void(const char*, double)> on_stage;
inline void on_signal(int) { g_stop = 1; }          // graceful: let mesh->close() run, or the device wedges

inline std::string esc(const std::string& in) {     // minimal JSON string escaping
    std::string o; o.reserve(in.size() + 8);
    for (char c : in) {
        switch (c) {
            case '"':  o += "\\\""; break;
            case '\\': o += "\\\\"; break;
            case '\n': o += "\\n";  break;
            case '\r': o += "\\r";  break;
            case '\t': o += "\\t";  break;
            default: if ((unsigned char)c < 0x20) o += fmt::format("\\u{:04x}", (int)c); else o += c; }
    }
    return o; }

// What one answered request produced. The demo already computes every field; this just keeps it so
// the socket loop can serialise it instead of only printing it.
struct Report {
    double rg = 0, exp_ = 0, conv = 0, scan = 0, fold = 0, dec = 0;   // per-stage ms
    double dev = 0, wall = 0, client = 0;                             // totals ms
    uint64_t p_exp = 0, p_conv = 0, p_scan = 0, p_fold = 0;           // programs BUILT (0 => replayed)
    uint32_t q = 0, bad = 0;
    std::vector<uint32_t> idx;
    std::vector<std::string> text;
    std::vector<bool> ok;
    // Crypto visibility for the UI: a few coefficients at each stage of query 0. Ciphertext limbs are
    // ~2^28 pseudorandom residues; the decrypted plaintext coefficients are small (< t = 257) and are
    // literally the ASCII of the row. Showing both is what makes "encrypted" concrete.
    // Per query, so a batch is represented honestly: Q independent plaintexts and ciphertexts that
    // meet only at the shared scan.
    std::vector<uint32_t> c0s;                       // one-hot slot each plaintext query encodes
    std::vector<std::string> bitss;                  // fold bits, sent separately as RGSW ciphertexts
    std::vector<std::vector<uint32_t>> ct_qs, ct_anss, pt_outs;
};

}  // namespace serve

int main(int argc, char** argv) {
    const char* qpath = "reference/pir/query65536.bin";
    const char* fpath = "reference/pir/db65536.fold";
    const char* tpath = "reference/pir/db65536.txt";
    const char* ppath = "reference/pir/db65536.pir";   // only for the isolation checks, not the demo path
    bool checks = false, interactive = false, resident = true;
    std::string serve_path;                             // --serve [path]: UI backend, owns the device
    std::string warm_widths = "1";                      // --warm 1,2 : pay these widths' cold pass at boot
    int64_t want_idx = -1;                              // >=0: generate this index with the C++ client
    std::vector<uint32_t> batch_idx;                    // --batch: answer these in ONE scan
    for (int i = 1; i < argc; ++i) {
        if (!std::strcmp(argv[i], "--query") && i + 1 < argc) qpath = argv[++i];
        else if (!std::strcmp(argv[i], "--fold") && i + 1 < argc) fpath = argv[++i];
        else if (!std::strcmp(argv[i], "--txt") && i + 1 < argc) tpath = argv[++i];
        else if (!std::strcmp(argv[i], "--pir") && i + 1 < argc) ppath = argv[++i];
        else if (!std::strcmp(argv[i], "--idx") && i + 1 < argc) want_idx = std::atoll(argv[++i]);
        else if (!std::strcmp(argv[i], "--checks")) checks = true;
        else if (!std::strcmp(argv[i], "--stream")) resident = false;
        else if (!std::strcmp(argv[i], "--batch") && i + 1 < argc) {
            const std::string a = argv[++i];
            if (a.find(',') == std::string::npos && a.size() <= 2) {      // "--batch 16" -> spread them out
                const uint32_t nq = (uint32_t)std::atoi(a.c_str());
                for (uint32_t j = 0; j < nq; ++j) batch_idx.push_back(j * 4099 + 7);
            } else { size_t pos = 0; while (pos <= a.size()) { const size_t c = a.find(',', pos);
                batch_idx.push_back((uint32_t)std::atoi(a.substr(pos, c - pos).c_str()));
                if (c == std::string::npos) break; pos = c + 1; } } }
        else if (!std::strcmp(argv[i], "--warm") && i + 1 < argc) warm_widths = argv[++i];
        else if (!std::strcmp(argv[i], "--serve")) serve_path = (i + 1 < argc && argv[i+1][0] != '-')
                                                        ? argv[++i] : "/tmp/pir_demo.sock";
        else if (!std::strcmp(argv[i], "-i") || !std::strcmp(argv[i], "--interactive")) interactive = true;
        else { fmt::print(stderr, "unknown arg {}\n", argv[i]); return 2; } }

    // A UI polling us needs to distinguish "starting" from "not running", and the socket does not
    // exist until after DB residency and key prep (~10 s). Publish a state file first thing.
    if (!serve_path.empty()) {
        // Redirected stdout is block-buffered, so a long-lived daemon's log sits empty for minutes and
        // looks hung. Line-buffer it: the log is the operator's only window into what the device is doing.
        std::setvbuf(stdout, nullptr, _IOLBF, 0);
        FILE* st = std::fopen((serve_path + ".state").c_str(), "w");
        if (st) { std::fputs("starting\n", st); std::fclose(st); } }

    // ---------------- client key bundle (the query file's index-independent part) ----------------
    std::ifstream fq(qpath, std::ios::binary);
    if (!fq) { fmt::print(stderr, "cannot open {}\n", qpath); return 2; }
    uint32_t qh[10]; fq.read((char*)qh, sizeof(qh));
    if (qh[0] != 0x51363553u) { fmt::print(stderr, "bad query magic in {}\n", qpath); return 2; }
    const uint32_t n = qh[1], K = qh[2], ell = qh[3], Bgad = qh[4], N0 = qh[5], m_exp = qh[6],
                   nfold = qh[7], file_idx = qh[8], t_plain = qh[9];
    if (n != N || K != 3) { fmt::print(stderr, "demo needs n=2048, K=3\n"); return 2; }
    std::vector<uint32_t> primes(K); fq.read((char*)primes.data(), 4 * K);
    auto rv = [&]{ std::vector<uint32_t> v(N); fq.read((char*)v.data(), 4 * N); return v; };
    std::vector<int32_t> s(N); fq.read((char*)s.data(), 4 * N);                       // client secret
    std::vector<std::vector<uint32_t>> file_query(2 * K);
    for (uint32_t comp = 0; comp < 2; ++comp) for (uint32_t ch = 0; ch < K; ++ch) file_query[comp*K+ch] = rv();
    std::vector<std::vector<std::vector<std::vector<uint32_t>>>> Klvl(                // [lvl][ch][k*2+col]
        m_exp, std::vector<std::vector<std::vector<uint32_t>>>(K, std::vector<std::vector<uint32_t>>(ell*2)));
    for (uint32_t a = 0; a < m_exp; ++a) for (uint32_t ch = 0; ch < K; ++ch)
        for (uint32_t k = 0; k < ell; ++k) for (uint32_t col = 0; col < 2; ++col) Klvl[a][ch][k*2+col] = rv();
    uint32_t has_gold = 0; fq.read((char*)&has_gold, 4);
    if (has_gold) for (uint32_t k = 0; k < N0; ++k) for (uint32_t i = 0; i < 2*K; ++i) (void)rv();
    const uint32_t twoL = 2 * ell;
    std::vector<std::vector<std::vector<uint32_t>>> file_selb(                         // [fold][row*2+col][ch]
        nfold, std::vector<std::vector<uint32_t>>(twoL * 2, std::vector<uint32_t>()));
    { std::vector<std::vector<std::vector<std::vector<uint32_t>>>> tmp(
          nfold, std::vector<std::vector<std::vector<uint32_t>>>(twoL*2, std::vector<std::vector<uint32_t>>(K)));
      for (uint32_t f = 0; f < nfold; ++f) for (uint32_t r = 0; r < twoL; ++r)
          for (uint32_t col = 0; col < 2; ++col) for (uint32_t ch = 0; ch < K; ++ch) tmp[f][r*2+col][ch] = rv();
      // flatten to [f][rc][ch] -> keep as a 4-D-ish structure the stages below index directly
      file_selb.clear(); file_selb.resize(nfold);
      for (uint32_t f = 0; f < nfold; ++f) { file_selb[f].resize(twoL*2);
          for (uint32_t rc = 0; rc < twoL*2; ++rc) { file_selb[f][rc].resize((size_t)K * N);
              for (uint32_t ch = 0; ch < K; ++ch)
                  std::copy(tmp[f][rc][ch].begin(), tmp[f][rc][ch].end(), file_selb[f][rc].begin() + (size_t)ch * N); } } }
    if (!fq) { fmt::print(stderr, "short read on {}\n", qpath); return 2; }

    // ---------------- folded database header ----------------
    uint32_t fh[8];
    { std::ifstream ff(fpath, std::ios::binary);
      if (!ff) { fmt::print(stderr, "cannot open {}\n", fpath); return 2; }
      ff.read((char*)fh, sizeof(fh));
      if (fh[0] != 0x50464C44u) { fmt::print(stderr, "bad fold magic in {}\n", fpath); return 2; } }
    const uint32_t n_rows = fh[3], N0f = fh[4], rest = fh[5], KB = fh[6], MB = fh[7];
    if (N0f != N0 || rest != (1u << nfold) || n_rows != N0 * rest) {
        fmt::print(stderr, "query/database shape mismatch\n"); return 2; }

    std::vector<std::string> rows;                    // only to confirm what came back; never an input
    { std::ifstream ft(tpath); std::string line; while (std::getline(ft, line)) rows.push_back(line); }

    fmt::print("=== OnionPIR demo: {} rows x {} ASCII chars, one n150 =========================\n", n_rows, N);
    fmt::print("  config   n={} K={} ell={} B={} t={}  |  N0={} x rest={} ({} folds)\n",
               n, K, ell, Bgad, t_plain, N0, rest, nfold);

    bool pass = true;
    try {
        auto mesh = distributed::MeshDevice::create_unit_mesh(0, DEFAULT_L1_SMALL_SIZE, 64u << 20);
        auto& cq = mesh->mesh_command_queue();
        Engine eng(mesh.get(), &cq, primes, ell, Bgad);
        Crt C(primes, t_plain);
        const uint32_t sOT = N, MT = T;                    // slot-tiles per channel; m-tile = 32 rows
        // Q queries share one scan: each contributes 2 of the matmul's 32 output columns.  Q can change
        // between batches (you can type a different number of indices), and the buffer sizes and the
        // recorded programs both depend on it — so a change reallocates and clears the caches, which
        // makes the next batch a cold one.  Keeping the count the same keeps you in the warm path.
        uint32_t Q = 0, COLS = 0;
        // Verified at Q<=4.  Q=16 (the full 32 columns) did NOT finish its program-building pass in
        // 12 minutes in testing, twice, and the cause is not yet understood — the per-query program
        // count is only linear in Q, so something else is superlinear.  Say so rather than let a demo
        // appear to hang.
        if (Q > 4) fmt::print("  WARNING: batch >4 is unverified; Q=16 did not complete its cold pass "
                              "in testing. Expect a very long first batch or a hang.\n");
        // buffers that must survive the scratch pool's resets (the pool recycles by call order, so a
        // buffer allocated while pooling is on can be handed back out as scratch later)
        auto persist = [&](uint32_t nt, uint32_t pg){ const bool wason = eng.pooling; eng.pooling = false;
                                                      auto b = eng.mkbuf(nt, pg); eng.pooling = wason; return b; };

        // ---- the host client: same secret key, so the Galois keys above stay valid ----
        auto t_cli = clk::now();
        pirclient::Client cli(primes, s, t_plain, ell, Bgad, N0, nfold, N);
        fmt::print("  client   host key setup (RGSW(s) + transforms): {:.0f} ms\n", ms_since(t_cli));

        // The host NTT is encode_db.cpp's, which test_db_encode_check proved bit-exact against the
        // device.  Key prep uses it instead of a device round-trip per polynomial (4.4 s -> 40 ms),
        // so confirm the equality here rather than assume it — a wrong NTT would be silent.
        // ntt_shoup, not ntt: every butterfly's `% q` becomes a multiply-high plus a conditional
        // subtract (Shoup, tables built in make_chan).  Same output -- the check below is against the
        // DEVICE, so if it were not the same output this would fail loudly rather than drift.  This
        // path runs 672 transforms per query for the fold RGSWs, on a 4-core host, so it is the
        // largest host-side term in the answer.
        auto hntt = [&](uint32_t ch, const std::vector<uint32_t>& x) {
            std::vector<uint32_t> o(N); pirclient::ntt_shoup(cli.ch[ch], x.data(), o.data()); return o; };
        { std::mt19937 rg(11); bool ok = true;
          for (uint32_t ch = 0; ch < K; ++ch) { std::vector<uint32_t> x(N);
              for (auto& v : x) v = rg() % primes[ch];
              auto a = hntt(ch, x), b = eng.fwd2048(eng.CH[ch], x);
              for (uint32_t i = 0; i < N; ++i) ok &= (a[i] == b[i]); }
          fmt::print("  check    host NTT == device fwd2048, all channels -> {}\n", ok ? "ok" : "FAIL");
          if (!ok) { fmt::print(stderr, "host/device NTT disagree; refusing to run\n"); return 2; }
          pass &= ok; }

        // ---- Galois keys: NTT + Montgomery, once (index-independent) ----
        auto t_key = clk::now();
        std::vector<std::vector<std::vector<MeshBuf>>> KnB(m_exp, std::vector<std::vector<MeshBuf>>(K, std::vector<MeshBuf>(2)));
        for (uint32_t a = 0; a < m_exp; ++a) for (uint32_t ch = 0; ch < K; ++ch) for (uint32_t col = 0; col < 2; ++col) {
            std::vector<uint32_t> buf((size_t)2 * ell * ELEMS);
            for (uint32_t k = 0; k < ell; ++k) {
                auto tl = til2(eng.to_mont(ch, hntt(ch, Klvl[a][ch][k*2+col])));
                std::copy(tl.begin(), tl.end(), buf.begin() + (size_t)2 * k * ELEMS); }
            auto b = persist(2 * ell, I32); eng.wrb(b, buf); KnB[a][ch][col] = b; }
        distributed::Finish(cq);
        fmt::print("  key prep Galois keys -> device: {:.0f} ms\n", ms_since(t_key));

        // ---- resident working set (allocated before the pool so it cannot be recycled as scratch) ----
        std::vector<MeshBuf> sX(K), bQ(K);
        for (uint32_t ch = 0; ch < K; ++ch) sX[ch] = persist(KB * sOT, I32);        // gathered query slots
        auto sW    = persist(KB * sOT * NB * NB, I8);                                // one m-tile's int8 fold
        // The whole folded database is 6.0 GB of the n150's 12 GB.  Holding it removes a 1.7 s
        // host->device stream from EVERY query; if it does not fit alongside the expand working set,
        // fall back to streaming rather than failing.
        std::vector<MeshBuf> sWr;
        auto sPar  = persist(sOT, I32), sAcc0 = persist(sOT, I32), sAcc1 = persist(sOT, I32);
        MeshBuf bAntt;                                                               // scan out, all Q queries
        std::vector<MeshBuf> bacc;                                                   // fold input per query
        std::vector<int8_t> Wb((size_t)KB * sOT * NB * NB * ELEMS);
        const std::vector<uint32_t> zero((size_t)sOT * ELEMS, 0);
        std::ifstream ff(fpath, std::ios::binary);
        if (resident) { auto t_r = clk::now();
            try { for (uint32_t i = 0; i < MB * K; ++i) sWr.push_back(persist(KB * sOT * NB * NB, I8)); }
            catch (const std::exception& e) { sWr.clear();
                fmt::print("  database  does not fit resident ({}); streaming per m-tile instead\n", e.what()); }
            if (!sWr.empty()) {
                for (uint32_t mt = 0; mt < MB; ++mt) for (uint32_t ch = 0; ch < K; ++ch) {
                    const size_t per_mt = (size_t)K * KB * N * NB * NB * ELEMS;
                    ff.clear();
                    ff.seekg((std::streamoff)(sizeof(fh) + (size_t)mt*per_mt + (size_t)ch*KB*N*NB*NB*ELEMS));
                    ff.read((char*)Wb.data(), (std::streamsize)Wb.size());
                    if (!ff) { fmt::print(stderr, "short read on {}\n", fpath); return 2; }
                    distributed::EnqueueWriteMeshBuffer(cq, sWr[mt*K+ch], Wb, false); }
                distributed::Finish(cq);
                fmt::print("  database  {:.1f} GB folded DB resident on device: {:.0f} ms (once)\n",
                           (double)MB*K*Wb.size()/(1ull<<30), ms_since(t_r)); } }
        // The two per-query INPUTS also have to be fixed buffers, re-filled in place each query:
        // program reuse bakes addresses, so reallocating these would leave the cached programs
        // reading the previous query's memory — wrong answer, no error.
        auto bquery = persist(eng.ctb_tiles(1), I32);
        std::vector<std::vector<std::vector<MeshBuf>>> Cb(                 // ONE set, refilled per query:
            nfold, std::vector<std::vector<MeshBuf>>(K, std::vector<MeshBuf>(2)));   // folds run serially
        for (uint32_t f = 0; f < nfold; ++f) for (uint32_t ch = 0; ch < K; ++ch)
            for (uint32_t col = 0; col < 2; ++col) Cb[f][ch][col] = persist(4 * ell, I32);
        eng.prewarm_batch(N0);
        eng.pool_enable(true);
        // POOL ARENAS.  The three sections (expand / scan / folds) each allocate a different sequence,
        // so a plain pool_reset() between them makes the pool see a size mismatch, drop its tail and
        // reallocate everything — every query, every m-tile.  Giving each section its own start mark
        // means each one replays its own sequence exactly: no churn, and the addresses the reused
        // programs baked in stay put.
        size_t arena_scan = SIZE_MAX, arena_fold = SIZE_MAX;
        auto resize_for = [&](uint32_t q) {
            if (q == Q) return;                       // same width: stay on the warm, cached path
            if (Q) fmt::print("  batch width {} -> {}: reallocating and rebuilding programs "
                              "(this batch will be a cold one)\n", Q, q);
            Q = q; COLS = 2 * Q;
            eng.caches_clear(); arena_scan = arena_fold = SIZE_MAX;   // baked addresses are now invalid
            for (uint32_t ch = 0; ch < K; ++ch) bQ[ch] = persist(2 * COLS * N0, I32);
            bAntt = persist(MT * COLS * 2, I32);
            bacc.assign(Q, nullptr);
            for (uint32_t qi = 0; qi < Q; ++qi) bacc[qi] = persist(eng.ctb_tiles(rest), I32); };
        // STEP 4 of the host-side ladder: reuse the programs.  The op sequence is identical on every
        // query (same shapes, same loop bounds), so the index-replayed workload cache is sufficient —
        // query 1 builds and records, every later query re-enqueues.  This is also the prerequisite for
        // MeshTrace, which cannot capture a program build at all.
        eng.wl_enable(true);

        // =============================================================================================
        // One BATCH of Q queries, end to end.  Q=1 is the interactive path.  Q>1 shares ONE scan — the
        // whole point of batching: the DB-linear work is fixed by the database, and a single query
        // occupies only 2 of the matmul's 32 output columns.  Expand and folds are inherently per query
        // (each has its own Subs tree and its own fold RGSWs) and stay in a loop.
        // =============================================================================================
        serve::Report LR;        // last answered request, for --serve (see pir_ui_plan.md)
        auto answer = [&](const std::vector<std::vector<std::vector<uint32_t>>>& queries,
                          const std::vector<std::vector<std::vector<std::vector<uint32_t>>>>& selbs,
                          const std::vector<uint32_t>& idxs, bool verbose) -> std::vector<std::string> {
            std::vector<std::string> out(Q);
            const uint32_t c0 = idxs[0] / rest, r_target = idxs[0] % rest;
            const std::string want0 = (idxs[0] < rows.size()) ? rows[idxs[0]] : std::string();
            eng.wl_reset();
            prof::reset();                       // per-pass host split: BUILD vs ENQ vs WR vs RD
            double rg_ms = 0, exp_ms = 0, conv_ms = 0, scan_ms = 0, io_ms = 0, fold_ms = 0, dec_ms = 0;
            uint64_t np_exp = 0, np_c1 = 0, np_sc = 0, np_fd = 0;
            std::vector<std::vector<std::vector<uint32_t>>> sel;

            // ---- STAGE 1, per query: expand 1 ct -> N0 selectors, then convert into THIS query's
            // two columns of the shared scan operand.  Conversion 1: poly (node, qi, comp) lands at
            // tile (node*COLS + qi*2 + comp)*2 + h, which is the (row, col) order the gather reads
            // with SR=COLS, SC=1 once its per-k-tile base is node0*2*COLS.
            for (uint32_t qi = 0; qi < Q; ++qi) {
                eng.pool_cur = 0;                            // arena A: the expand tree + conversion 1
                eng.upload_ctb_into(bquery, {queries[qi]});
                auto t_exp = clk::now(); const uint64_t p_exp0 = eng.n_prog;
                uint32_t Bl = 1; MeshBuf cts = bquery;
                for (uint32_t a = 0; a < m_exp; ++a) { const int64_t j = (int64_t)(N >> a) + 1;
                    auto comb = eng.mkctb(2 * Bl);               // [ c | x^-2^a * c ] as one 2B batch
                    eng.permute_ctb_into(cts, Bl, comb, 2 * Bl, 0,  1u, 0u);
                    eng.monomul_ctb_into(cts, Bl, comb, 2 * Bl, Bl, -(int64_t)(1u << a));
                    auto scr = eng.mkctb(2 * Bl), sbuf = eng.mkctb(2 * Bl);
                    eng.subs_levelB(comb, 2 * Bl, j, KnB[a], sbuf, scr);
                    auto nxt = eng.mkctb(2 * Bl); eng.ctadd_ctb(comb, sbuf, nxt, 2 * Bl);
                    cts = nxt; Bl *= 2; }
                distributed::Finish(cq);
                exp_ms += ms_since(t_exp); np_exp += eng.n_prog - p_exp0;
                if (serve::on_stage) serve::on_stage("expand", exp_ms);

                if (checks && qi == 0) {   // selectors must be a one-hot encryption of 1 at c0
                    sel = eng.download_ctb(cts, Bl);
                    uint32_t bad = 0;
                    for (uint32_t k : {c0, c0 ^ 1u, (c0 + 7) % N0}) {
                        auto m = decrypt(C, sel[k], K, s);
                        const uint32_t w0 = (k == c0) ? 1u : 0u;
                        bool ok = (m[0] == w0); for (uint32_t i = 1; i < N; ++i) ok &= (m[i] == 0);
                        if (!ok) ++bad; }
                    fmt::print("      check: selectors decrypt one-hot at c0={} -> {}\n", c0, bad ? "FAIL" : "ok");
                    pass &= (bad == 0); }

                auto t_c1 = clk::now(); const uint64_t p_c10 = eng.n_prog;
                for (uint32_t ch = 0; ch < K; ++ch) for (uint32_t comp = 0; comp < 2; ++comp)
                    eng.fwd2048_batchM(eng.CH[ch], cts, eng.ctb_grp(comp, ch, N0), 1, N0, N0,
                                       bQ[ch], (qi * 2 + comp) * 2, 2 * COLS, 1);
                distributed::Finish(cq);
                conv_ms += ms_since(t_c1); np_c1 += eng.n_prog - p_c10;
                if (serve::on_stage) serve::on_stage("convert", conv_ms);
                cts.reset();
                if (arena_scan == SIZE_MAX) arena_scan = eng.pool_cur; }

            // slot gather, once all Q queries sit in bQ
            { auto t_g = clk::now(); const uint64_t p0 = eng.n_prog;
              for (uint32_t ch = 0; ch < K; ++ch) for (uint32_t kt = 0; kt < KB; ++kt) for (uint32_t h = 0; h < 2; ++h)
                  eng.scan_gather(bQ[ch], sX[ch], std::min(T, N0 - kt * T), COLS, COLS, 1u,
                                  kt * sOT, h, kt * T * 2 * COLS);
              distributed::Finish(cq); conv_ms += ms_since(t_g); np_c1 += eng.n_prog - p0;
                if (serve::on_stage) serve::on_stage("convert", conv_ms); }

            if (checks) {   // both halves of conversion 1 for query 0, against the device's own NTT
                const uint32_t ch = 0;
                auto Qdev = eng.rdb(bQ[ch]); uint32_t badq = 0;
                for (uint32_t nd : {0u, 1u, c0, N0 - 1}) for (uint32_t comp = 0; comp < 2; ++comp) {
                    auto wn = eng.fwd2048(eng.CH[ch], sel[nd][comp*K+ch]);
                    for (uint32_t h = 0; h < 2; ++h) {
                        const size_t o = (size_t)((nd*COLS + comp)*2 + h) * ELEMS;
                        auto gt = unt1(std::vector<uint32_t>(Qdev.begin()+o, Qdev.begin()+o+ELEMS));
                        for (uint32_t i = 0; i < ELEMS; ++i) if (gt[i] != wn[h*ELEMS+i]) ++badq; } }
                uint32_t badx = 0; auto Xdev = eng.rdb(sX[ch]);
                for (uint32_t kt : {0u, KB - 1}) {
                    std::vector<std::vector<uint32_t>> qn(T * 2);
                    for (uint32_t row = 0; row < T; ++row) for (uint32_t col = 0; col < 2; ++col)
                        qn[row*2+col] = eng.fwd2048(eng.CH[ch], sel[kt*T+row][col*K+ch]);
                    for (uint32_t h = 0; h < 2; ++h) { const uint32_t jl = 5 + 17 * kt;
                        const size_t o = (size_t)(kt*sOT + h*ELEMS + jl) * ELEMS;
                        for (uint32_t row = 0; row < T; ++row) for (uint32_t col = 0; col < 2; ++col)
                            if (Xdev[o + ((row/16)*2+col/16)*256+(row%16)*16+(col%16)] != qn[row*2+col][h*ELEMS+jl]) ++badx; } }
                fmt::print("      check: selector NTT -> scan layout {} | slot gather {}\n",
                           badq ? "FAIL" : "ok", badx ? "FAIL" : "ok");
                pass &= (badq == 0 && badx == 0); }

            // ---- STAGE 2: ONE scan over all 65 536 rows, serving every query in the batch ----
            { const uint64_t p_sc0 = eng.n_prog;
              for (uint32_t mt = 0; mt < MB; ++mt) for (uint32_t ch = 0; ch < K; ++ch) {
                auto t_io = clk::now();
                MeshBuf dbbuf = sW;
                if (!sWr.empty()) { dbbuf = sWr[mt*K+ch]; }
                else {
                    const size_t per_mt = (size_t)K * KB * N * NB * NB * ELEMS;
                    ff.clear();
                    ff.seekg((std::streamoff)(sizeof(fh) + (size_t)mt * per_mt + (size_t)ch * KB * N * NB * NB * ELEMS));
                    ff.read((char*)Wb.data(), (std::streamsize)Wb.size());
                    if (!ff) { fmt::print(stderr, "short read on {}\n", fpath); return out; }
                    distributed::EnqueueWriteMeshBuffer(cq, sW, Wb, false); }
                eng.wrb(sAcc0, zero);
                distributed::Finish(cq);
                io_ms += ms_since(t_io);

                auto t_s = clk::now();
                eng.pool_cur = arena_scan;                   // arena B: scan scratch + conversions 2/3
                eng.scan_mtile(eng.CH[ch], sX[ch], dbbuf, sPar, sAcc0, sAcc1, bAntt, KB, sOT, MT, COLS);
                // conversions 2 and 3: eval -> coefficients, into each query's B=rest fold batch at this
                // m-tile's node offset (m-tile mt supplies rows mt*32 .. mt*32+31)
                for (uint32_t qi = 0; qi < Q; ++qi) for (uint32_t comp = 0; comp < 2; ++comp)
                    eng.inv2048_batchM(eng.CH[ch], bAntt, (qi * 2 + comp) * 2, 2 * COLS, 1, MT,
                                       bacc[qi], eng.ctb_grp(comp, ch, rest) + mt * MT, 1, rest);
                distributed::Finish(cq);
                scan_ms += ms_since(t_s);
                if (serve::on_stage) serve::on_stage("scan", scan_ms);
                if (arena_fold == SIZE_MAX) arena_fold = eng.pool_cur;

                if (checks) {   // the scan with the REAL selectors, vs a host golden from bQ + db65536.pir
                    const uint32_t rl = r_target % T, rr = mt * T + rl, q = primes[ch];
                    const uint32_t rinv = (uint32_t)mont::modular_inverse(((uint64_t)1 << 32) % q, q);
                    auto Qd = eng.rdb(bQ[ch]); auto Ad = eng.rdb(bAntt);
                    std::ifstream fp(ppath, std::ios::binary);
                    uint32_t ph2[8]; fp.read((char*)ph2, sizeof(ph2));
                    const size_t per_ch = (size_t)n_rows * N;
                    std::vector<std::vector<uint32_t>> g(2, std::vector<uint32_t>(N, 0));
                    for (uint32_t k = 0; k < N0; ++k) {
                        std::vector<uint32_t> tl(N);
                        fp.seekg((std::streamoff)(sizeof(ph2) + ((size_t)ch*per_ch + ((size_t)k*rest + rr)*N)*4));
                        fp.read((char*)tl.data(), N * 4);
                        auto db = unt2(tl);
                        for (auto& v : db) v = (uint32_t)((uint64_t)v * rinv % q);
                        for (uint32_t comp = 0; comp < 2; ++comp) { std::vector<uint32_t> qq(N);
                            for (uint32_t h = 0; h < 2; ++h) { const size_t o = (size_t)((k*COLS + comp)*2 + h)*ELEMS;
                                auto u = unt1(std::vector<uint32_t>(Qd.begin()+o, Qd.begin()+o+ELEMS));
                                std::copy(u.begin(), u.end(), qq.begin() + (size_t)h*ELEMS); }
                            for (uint32_t j = 0; j < N; ++j)
                                g[comp][j] = (uint32_t)(((uint64_t)g[comp][j] + (uint64_t)db[j]*qq[j]) % q); } }
                    uint32_t bads = 0;
                    for (uint32_t comp = 0; comp < 2; ++comp) for (uint32_t h = 0; h < 2; ++h) {
                        const size_t o = (size_t)((rl*COLS + comp)*2 + h)*ELEMS;
                        auto gt = unt1(std::vector<uint32_t>(Ad.begin()+o, Ad.begin()+o+ELEMS));
                        for (uint32_t i = 0; i < ELEMS; ++i) if (gt[i] != g[comp][h*ELEMS+i]) ++bads; }
                    fmt::print("      check: scan mt{} ch{} (row {}) vs host golden -> {}\n",
                               mt, ch, rr, bads ? "FAIL" : "ok");
                    pass &= (bads == 0); } }
              np_sc = eng.n_prog - p_sc0; }

            if (checks) {   // acc[r_target] must already BE query 0's answer
                auto acc = eng.download_ctb(bacc[0], rest);
                auto got = decode(decrypt(C, acc[r_target], K, s));
                fmt::print("      check: post-scan acc[{}] decodes to the target row -> {}\n",
                           r_target, (got == want0) ? "ok" : "FAIL");
                pass &= (got == want0); }

            // ---- STAGE 3, per query: 7 binary folds, 128 rows -> 1, then decrypt ----
            LR.ct_anss.clear(); LR.pt_outs.clear();
            for (uint32_t qi = 0; qi < Q; ++qi) {
                // this query's fold RGSWs -> device (672 host NTTs + Montgomery; folds are independent,
                // so transform in parallel and keep only the enqueues serial — one command queue)
                auto t_rg = clk::now();
                std::vector<std::vector<std::vector<std::vector<uint32_t>>>> Cn(
                    nfold, std::vector<std::vector<std::vector<uint32_t>>>(K, std::vector<std::vector<uint32_t>>(twoL * 2)));
                { std::vector<std::thread> th;
                  for (uint32_t f = 0; f < nfold; ++f) th.emplace_back([&, f]{
                      for (uint32_t ch = 0; ch < K; ++ch) for (uint32_t rc = 0; rc < twoL * 2; ++rc) {
                          std::vector<uint32_t> pp(selbs[qi][f][rc].begin() + (size_t)ch * N,
                                                   selbs[qi][f][rc].begin() + (size_t)(ch + 1) * N);
                          Cn[f][ch][rc] = eng.to_mont(ch, hntt(ch, pp)); } });
                  for (auto& x : th) x.join(); }
                for (uint32_t f = 0; f < nfold; ++f) eng.rgsw_operand_into(Cn[f], Cb[f]);
                rg_ms += ms_since(t_rg);
                if (serve::on_stage) serve::on_stage("fold_rgsw", rg_ms);

                auto t_f = clk::now(); const uint64_t p_fd0 = eng.n_prog;
                eng.pool_cur = arena_fold;                   // arena C: the fold chain
                MeshBuf acc = bacc[qi]; uint32_t Bc = rest;
                for (uint32_t f = 0; f < nfold; ++f) { acc = eng.fold_levelB(acc, Bc, Cb[f]); Bc /= 2; }
                distributed::Finish(cq);
                fold_ms += ms_since(t_f); np_fd += eng.n_prog - p_fd0;
                if (serve::on_stage) serve::on_stage("folds", fold_ms);
                auto ans = eng.download_ctb(acc, 1);
                auto t_d = clk::now();
                { auto pt = decrypt(C, ans[0], K, s);
                  LR.ct_anss.push_back({ans[0][0].begin(),
                                        ans[0][0].begin() + std::min<size_t>(10, ans[0][0].size())});
                  LR.pt_outs.push_back({pt.begin(), pt.begin() + std::min<size_t>(16, pt.size())});
                  out[qi] = decode(pt); }
                dec_ms += ms_since(t_d);
                if (serve::on_stage) serve::on_stage("decrypt", dec_ms); }

            if (verbose) {
                const double dev = rg_ms + exp_ms + conv_ms + scan_ms + fold_ms;
                LR.rg = rg_ms; LR.exp_ = exp_ms; LR.conv = conv_ms;
                LR.scan = scan_ms; LR.fold = fold_ms; LR.dec = dec_ms; LR.dev = dev;
                LR.p_exp = np_exp; LR.p_conv = np_c1; LR.p_scan = np_sc; LR.p_fold = np_fd;
                // Printed in EXECUTION order. "fold RGSWs" is per-query preparation of the fold
                // operands (672 host NTTs + Montgomery, then rgsw_operand_into) and runs in stage 3,
                // just before the folds that consume it -- NOT first, despite the old [0] label.
                fmt::print("  [1] expand {:.0f} ms | [2] convert {:.0f} ms | [3] scan {:.0f} ms (+{:.0f} ms DB)"
                           " | [4] fold RGSWs {:.0f} ms | [5] folds {:.0f} ms | [6] decrypt {:.0f} ms\n",
                           exp_ms, conv_ms, scan_ms, io_ms, rg_ms, fold_ms, dec_ms);
                fmt::print("  server on-device compute: {:.0f} ms", dev);
                if (Q > 1) fmt::print("  for {} queries = {:.0f} ms/query  (scan {:.1f} ms/query)",
                                      Q, dev / Q, scan_ms / Q);
                fmt::print("\n  programs: expand {} | convert {} | scan {} | folds {} | total {}\n",
                           np_exp, np_c1, np_sc, np_fd, np_exp + np_c1 + np_sc + np_fd);
                prof::report("pass"); }
            return out; };

        // =============================================================================================
        auto report = [&](uint32_t idx, const std::string& got) {
            const std::string head = fmt::format("{:05d}", idx);
            const bool idx_ok = (got.size() >= 5 && got.compare(0, 5, head) == 0);
            const std::string want = (idx < rows.size()) ? rows[idx] : std::string();
            const bool txt_ok = want.empty() || (got == want);
            fmt::print("\n  row {}:\n    \"{}\"\n", idx, got);
            fmt::print("  leading index matches request: {}   full row matches db65536.txt: {}\n\n",
                       idx_ok ? "YES" : "NO", want.empty() ? "(no text file)" : (txt_ok ? "YES" : "NO"));
            pass &= idx_ok && txt_ok; };

        // convert a client-generated query into the per-channel residues the device stages take
        auto to_device = [&](const pirclient::Client::Query& Q,
                             std::vector<std::vector<uint32_t>>& query,
                             std::vector<std::vector<std::vector<uint32_t>>>& selb) {
            query.assign(2 * K, {});
            for (uint32_t comp = 0; comp < 2; ++comp) for (uint32_t ch = 0; ch < K; ++ch)
                query[comp*K+ch] = cli.res(Q.ct[comp], ch);
            selb.assign(nfold, std::vector<std::vector<uint32_t>>(twoL * 2));
            for (uint32_t f = 0; f < nfold; ++f) for (uint32_t r = 0; r < twoL; ++r)
                for (uint32_t col = 0; col < 2; ++col) { auto& dst = selb[f][r*2+col]; dst.resize((size_t)K * N);
                    for (uint32_t ch = 0; ch < K; ++ch) { auto v = cli.res(Q.folds[f][r][col], ch);
                        std::copy(v.begin(), v.end(), dst.begin() + (size_t)ch * N); } } };

        // ---- one place that answers a list of indices, used by every mode -------------------------
        auto run_indices = [&](const std::vector<uint32_t>& idxs, bool twice) {
            const uint32_t q = (uint32_t)idxs.size();
            if (2 * q > T) { fmt::print("  at most {} indices per batch (each uses 2 of {} matmul columns)\n",
                                        T / 2, T); return; }
            // Measured on p150b: Q=5 is CORRECT (5/5) but its cold pass is ~571 s against ~22 s at Q=3,
            // while steady state improves (263 ms/query, scan 39.8 ms/query). The cost is compile/record
            // time, not correctness -- and it is paid once per batch WIDTH, since resize_for() clears the
            // caches. Above Q=5 is unprofiled; Q=16 has never finished a cold pass.
            if (q > 4) fmt::print("  NOTE: Q={} cold pass is slow to build (~571 s measured at Q=5, vs ~22 s "
                                  "at Q=3) — results are correct, steady state is ~263 ms/query. Above Q=5 "
                                  "is unprofiled.\n", q);
            resize_for(q);
            auto t_q = clk::now();
            std::vector<std::vector<std::vector<uint32_t>>> queries(q);
            std::vector<std::vector<std::vector<std::vector<uint32_t>>>> selbs(q);
            std::vector<std::string> what;
            LR.c0s.clear(); LR.bitss.clear(); LR.ct_qs.clear();
            for (uint32_t qi = 0; qi < q; ++qi) {
                auto Qy = cli.make_query(idxs[qi]);
                to_device(Qy, queries[qi], selbs[qi]);
                { LR.c0s.push_back(Qy.c0);
                  std::string bs; for (auto bt : Qy.bits) bs += char('0' + bt);
                  LR.bitss.push_back(bs);
                  LR.ct_qs.push_back({queries[qi][0].begin(),
                                      queries[qi][0].begin() + std::min<size_t>(10, queries[qi][0].size())}); }
                std::string b; for (auto x : Qy.bits) b += char('0' + x);
                what.push_back(fmt::format("idx {} -> c0={} bits={}", idxs[qi], Qy.c0, b)); }
            LR.client = ms_since(t_q);
            fmt::print("  client   generated {} quer{} in {:.0f} ms ({:.0f} ms each)\n",
                       q, q == 1 ? "y" : "ies", ms_since(t_q), ms_since(t_q) / q);
            for (auto& w : what) fmt::print("    {}\n", w);
            if (q > 1) fmt::print("  one scan serves all {} of them ({} of {} matmul columns used)\n",
                                  q, 2 * q, T);
            std::vector<std::string> cold;
            if (twice) { auto t_c = clk::now();
                cold = answer(queries, selbs, idxs, true);
                fmt::print("  ---- cold pass above ({:.0f} ms); steady state below ----\n", ms_since(t_c)); }
            auto t_a = clk::now();
            auto got = answer(queries, selbs, idxs, true);
            const double wall = ms_since(t_a);
            LR.wall = wall; LR.q = q; LR.idx = idxs; LR.text.assign(q, ""); LR.ok.assign(q, false);
            for (uint32_t qi = 0; qi < q; ++qi) if (!cold.empty() && cold[qi] != got[qi]) {
                fmt::print("  cold and warm disagree on row {}\n", idxs[qi]); pass = false; }
            uint32_t bad = 0;
            for (uint32_t qi = 0; qi < q; ++qi) {
                const std::string head = fmt::format("{:05d}", idxs[qi]);
                const std::string wantq = (idxs[qi] < rows.size()) ? rows[idxs[qi]] : std::string();
                const bool ok = got[qi].size() >= 5 && got[qi].compare(0, 5, head) == 0
                                && (wantq.empty() || got[qi] == wantq);
                if (!ok) ++bad;
                LR.text[qi] = got[qi]; LR.ok[qi] = ok;
                fmt::print("  {} row {:5}: \"{}\"\n", ok ? "ok  " : "FAIL", idxs[qi], got[qi]); }
            LR.bad = bad;
            fmt::print("  {}/{} correct | {:.0f} ms", q - bad, q, wall);
            if (q > 1) fmt::print(" for the batch = {:.0f} ms/query", wall / q);
            fmt::print("\n\n");
            pass &= (bad == 0); };

        // parse "7", "7,100, 9" or "7 100 9" into row indices; empty on any bad token
        auto parse_indices = [&](const std::string& line) {
            std::vector<uint32_t> v; std::string tok;
            auto flush = [&]{ if (tok.empty()) return true;
                char* e = nullptr; const long long x = std::strtoll(tok.c_str(), &e, 10);
                // Validate BEFORE clearing: `e` points into tok's own buffer, and tok.clear() nulls the
                // byte it addresses, so `*e` read afterwards is always '\0'. Every non-numeric token
                // therefore passed as index 0 -- "abc" silently returned row 0 with a verified badge.
                const bool bad = (*e != '\0') || x < 0 || x >= (long long)n_rows;
                tok.clear();
                if (bad) return false;
                v.push_back((uint32_t)x); return true; };
            for (char c : line) { if (c == ',' || c == ' ' || c == '\t') { if (!flush()) return std::vector<uint32_t>{}; }
                                  else tok.push_back(c); }
            if (!flush()) return std::vector<uint32_t>{};
            return v; };

        if (!serve_path.empty()) {
            // Backend for the browser UI (docs/pir/pir_ui_plan.md). Owns the device for its lifetime:
            // the cold pass is per process, so this must outlive the frontend.
            // sigaction, NOT std::signal: glibc's signal() implies SA_RESTART, which auto-restarts the
            // blocking accept() so the handler never unblocks it and SIGTERM does nothing. Clearing
            // SA_RESTART makes accept() return EINTR so we can shut the mesh down cleanly -- and an
            // abrupt kill is precisely what leaves this device wedged for the next run.
            { struct sigaction sa{}; sa.sa_handler = serve::on_signal; sigemptyset(&sa.sa_mask);
              sa.sa_flags = 0;                                    // no SA_RESTART
              ::sigaction(SIGINT, &sa, nullptr); ::sigaction(SIGTERM, &sa, nullptr); }
            std::signal(SIGPIPE, SIG_IGN);                       // a browser tab closing must not kill us
            const std::string lockp = serve_path + ".lock";
            int lockfd = ::open(lockp.c_str(), O_CREAT | O_RDWR, 0644);
            if (lockfd < 0 || ::flock(lockfd, LOCK_EX | LOCK_NB) != 0) {
                fmt::print(stderr, "  another --serve instance holds {}; the device is exclusive\n", lockp);
                return 2; }
            ::unlink(serve_path.c_str());
            int srv = ::socket(AF_UNIX, SOCK_STREAM, 0);
            sockaddr_un sa{}; sa.sun_family = AF_UNIX;
            std::strncpy(sa.sun_path, serve_path.c_str(), sizeof(sa.sun_path) - 1);
            if (srv < 0 || ::bind(srv, (sockaddr*)&sa, sizeof(sa)) != 0 || ::listen(srv, 4) != 0) {
                fmt::print(stderr, "  cannot listen on {}\n", serve_path); return 2; }

            auto send = [&](int fd, const std::string& l) {
                const std::string o = l + "\n"; ssize_t r = ::write(fd, o.data(), o.size()); (void)r; };
            auto est_cold_s = [](uint32_t q) {           // measured: Q=1 ~4.3 s, Q=3 ~18 s, Q=5 ~579 s
                return q <= 1 ? 5 : q <= 2 ? 10 : q <= 3 ? 20 : q <= 4 ? 120 : 600; };
            // The plaintext query's non-zero value. The server's expansion tree has m_exp levels and each
            // doubles the selected coefficient, so the client pre-scales by (2^m_exp)^-1 mod t; the
            // expanded selectors then decrypt to exactly 1.
            uint32_t slot_val = 0;
            { const uint64_t p2 = (1ull << m_exp) % t_plain;
              for (uint32_t x = 1; x < t_plain; ++x) if (p2 * x % t_plain == 1) { slot_val = x; break; } }
            auto join_u32 = [](const std::vector<uint32_t>& v) {
                std::string o; for (size_t i = 0; i < v.size(); ++i) o += fmt::format("{}{}", i ? "," : "", v[i]);
                return o; };
            auto result_json = [&]() {
                // One entry per query: each is its own plaintext and its own ciphertext. They share
                // nothing until the scan, and the UI should show that rather than only query 0.
                std::string per_query;
                for (uint32_t i = 0; i < LR.q; ++i) {
                    auto at = [&](const std::vector<std::vector<uint32_t>>& v, uint32_t k) {
                        return k < v.size() ? join_u32(v[k]) : std::string(); };
                    per_query += fmt::format(
                        "{}{{\"idx\":{},\"c0\":{},\"fold_bits\":\"{}\",\"col\":{},"
                        "\"ct_query\":[{}],\"ct_answer\":[{}],\"pt_out\":[{}]}}",
                        i ? "," : "", i < LR.idx.size() ? LR.idx[i] : 0,
                        i < LR.c0s.size() ? LR.c0s[i] : 0,
                        i < LR.bitss.size() ? LR.bitss[i] : std::string(), 2 * i,
                        at(LR.ct_qs, i), at(LR.ct_anss, i), at(LR.pt_outs, i)); }
                std::string rows;
                for (uint32_t i = 0; i < LR.q && i < LR.text.size(); ++i)
                    rows += fmt::format("{}{{\"idx\":{},\"text\":\"{}\",\"ok\":{}}}",
                                        i ? "," : "", LR.idx[i], serve::esc(LR.text[i]),
                                        LR.ok[i] ? "true" : "false");
                const uint64_t ptot = LR.p_exp + LR.p_conv + LR.p_scan + LR.p_fold;
                return fmt::format(
                    "{{\"ev\":\"result\",\"q\":{},\"verified\":{},\"rows_touched\":{},"
                    "\"wall_ms\":{:.1f},\"dev_ms\":{:.1f},\"client_ms\":{:.1f},"
                    "\"per_query_ms\":{:.1f},\"scan_per_query_ms\":{:.1f},"
                    "\"timings\":{{\"fold_rgsw\":{:.1f},\"expand\":{:.1f},\"convert\":{:.1f},"
                    "\"scan\":{:.1f},\"folds\":{:.1f},\"decrypt\":{:.1f}}},"
                    "\"programs\":{{\"expand\":{},\"convert\":{},\"scan\":{},\"folds\":{},\"total\":{}}},"
                    "\"crypto\":{{\"slot_val\":{},\"m_exp\":{},\"t\":{},\"n0\":{},\"cols_used\":{},"
                    "\"cols_total\":{},\"queries\":[{}]}},"
                    "\"rows\":[{}]}}",
                    LR.q, LR.bad == 0 ? "true" : "false", (unsigned)n_rows,
                    LR.wall, LR.dev, LR.client,
                    LR.q ? LR.wall / LR.q : 0.0, LR.q ? LR.scan / LR.q : 0.0,
                    LR.rg, LR.exp_, LR.conv, LR.scan, LR.fold, LR.dec,
                    LR.p_exp, LR.p_conv, LR.p_scan, LR.p_fold, ptot,
                    slot_val, m_exp, t_plain, N0, 2 * LR.q, T, per_query, rows); };

            // Warm the cheap width now so the first click is fast, not a 4 s stall.
            // Pre-pay the cold pass for each requested width. It cannot be cached to disk (the cost is
            // per-process device setup, not compilation -- see docs/pir/pir_ui_plan.md), so the only
            // lever is to pay it at boot instead of under the user's first click.
            auto t_w = clk::now();
            // ONE width only, and measured proof that a list would be pointless: resize_for() calls
            // caches_clear(), which wipes the whole workload cache rather than keeping one per width.
            // `--warm 1,2` cost 15 s and still left exactly one width warm -- switching 1->2 afterwards
            // rebuilt all 5382 programs anyway. Warm the width you will actually use.
            { const size_t c = warm_widths.find(',');
              if (c != std::string::npos)
                  fmt::print("  [serve] note: --warm takes ONE width; only the first survives, because a "
                             "width change clears the whole cache. Using {}.\n", warm_widths.substr(0, c));
              int w = std::atoi(warm_widths.substr(0, c).c_str());
              if (w <= 0 || (uint32_t)w > T / 2) w = 1;
              fmt::print("\n  [serve] warming Q={} ...\n", w);
              std::vector<uint32_t> ix; for (int j = 0; j < w; ++j) ix.push_back((uint32_t)j);
              run_indices(ix, /*twice=*/false); }
            fmt::print("  [serve] listening on {}  (warm-up {:.0f} ms)\n", serve_path, ms_since(t_w));
            { FILE* st = std::fopen((serve_path + ".state").c_str(), "w");
              if (st) { std::fputs("ready\n", st); std::fclose(st); } }

            auto handle = [&](int fd, std::string line) {
                while (!line.empty() && (line.back() == '\r' || line.back() == ' ')) line.pop_back();
                if (line.empty()) return;
                std::string op, args;
                if (line[0] == '{') {                        // tolerant JSON: pull "op" and the digits
                    const size_t o = line.find("\"op\"");
                    if (o != std::string::npos) { size_t q1 = line.find('"', line.find(':', o) + 1);
                        size_t q2 = (q1 == std::string::npos) ? q1 : line.find('"', q1 + 1);
                        if (q2 != std::string::npos) op = line.substr(q1 + 1, q2 - q1 - 1); }
                    const size_t b = line.find('[');
                    if (b != std::string::npos) { const size_t e = line.find(']', b);
                        if (e != std::string::npos) args = line.substr(b + 1, e - b - 1); }
                } else { const size_t sp = line.find(' ');
                    op = line.substr(0, sp);
                    if (sp != std::string::npos) args = line.substr(sp + 1); }

                if (op == "status") {
                    send(fd, fmt::format("{{\"ev\":\"status\",\"rows\":{},\"max_batch\":{},"
                                         "\"width\":{},\"ready\":true}}", (unsigned)n_rows, T / 2, Q));
                    return; }
                if (op == "quit") { serve::g_stop = 1; send(fd, "{\"ev\":\"bye\"}"); return; }
                if (op != "query" && op != "warm") {
                    send(fd, fmt::format("{{\"ev\":\"error\",\"msg\":\"unknown op '{}'\"}}",
                                         serve::esc(op))); return; }
                auto idxs = parse_indices(args);
                if (op == "warm" && idxs.empty()) idxs.assign(1, 0u);
                if (idxs.empty()) {
                    send(fd, fmt::format("{{\"ev\":\"error\",\"msg\":\"give row indices in [0,{})\"}}",
                                         (unsigned)n_rows)); return; }
                if (idxs.size() > T / 2) {
                    send(fd, fmt::format("{{\"ev\":\"error\",\"msg\":\"at most {} indices per batch\"}}",
                                         T / 2)); return; }
                const bool wc = ((uint32_t)idxs.size() != Q);
                send(fd, fmt::format("{{\"ev\":\"accepted\",\"q\":{},\"width_change\":{}}}",
                                     idxs.size(), wc ? "true" : "false"));
                if (wc) send(fd, fmt::format(
                    "{{\"ev\":\"cold\",\"q\":{},\"est_s\":{},"
                    "\"why\":\"width change clears the workload cache; this pass rebuilds it\"}}",
                    idxs.size(), est_cold_s((uint32_t)idxs.size())));
                serve::on_stage = [&](const char* nm, double ms) {
                    send(fd, fmt::format("{{\"ev\":\"stage\",\"name\":\"{}\",\"ms\":{:.1f}}}", nm, ms)); };
                run_indices(idxs, /*twice=*/false);
                serve::on_stage = nullptr;
                send(fd, result_json()); };

            while (!serve::g_stop) {
                int c = ::accept(srv, nullptr, nullptr);
                if (c < 0) { if (serve::g_stop) break; continue; }
                std::string buf; char tmp[1024];
                while (!serve::g_stop) {
                    const ssize_t n = ::read(c, tmp, sizeof(tmp));
                    if (n <= 0) break;
                    buf.append(tmp, (size_t)n);
                    size_t nl;
                    while ((nl = buf.find('\n')) != std::string::npos) {
                        const std::string one = buf.substr(0, nl); buf.erase(0, nl + 1); handle(c, one); } }
                ::close(c); }
            ::close(srv); ::unlink(serve_path.c_str()); ::unlink((serve_path + ".state").c_str());
            fmt::print("  [serve] stopped; closing the device cleanly\n");
        } else if (!batch_idx.empty()) {
            run_indices(batch_idx, /*twice=*/true);
        } else if (interactive) {
            fmt::print("\n  Type one row index, or several separated by commas/spaces to answer them in\n"
                       "  ONE shared scan (up to {}).  Range [0,{}).  'q' to quit.\n"
                       "    e.g.  777          a single query\n"
                       "          7,777,40000  three queries, one scan\n"
                       "  The server sees only encrypted queries; it touches every row either way.\n\n",
                       T / 2, n_rows);
            std::string line;
            while (true) {
                fmt::print("index> "); std::fflush(stdout);
                if (!std::getline(std::cin, line)) break;
                if (line.empty()) continue;
                if (line[0] == 'q' || line[0] == 'Q') break;
                auto idxs = parse_indices(line);
                if (idxs.empty()) { fmt::print("  give row indices in [0,{}), separated by commas or spaces\n", n_rows); continue; }
                run_indices(idxs, /*twice=*/false); }
        } else if (want_idx >= 0) {
            if ((uint32_t)want_idx >= n_rows) { fmt::print(stderr, "idx out of range\n"); return 2; }
            run_indices({(uint32_t)want_idx}, /*twice=*/false);
        } else {
            fmt::print("  query    from {} (reference client, idx={})\n", qpath, file_idx);
            resize_for(1);
            report(file_idx, answer({file_query}, {file_selb}, {file_idx}, true)[0]); }

        pass &= mesh->close();
    } catch (const std::exception& e) { fmt::print(stderr, "Exception:\n{}\n", e.what()); return 2; }
    if (pass) fmt::print("Demo Passed\n"); else fmt::print("Demo FAILED\n");
    return pass ? 0 : 1;
}
