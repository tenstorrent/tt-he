// pir_demo65536 — the real end-to-end OnionPIR demo over a 65 536-row ASCII database, on one n150.
//
// Everything the server does runs ON DEVICE, through exactly the OnionPIRv2-matched kernels
// (docs/pir/ONION_MATCH_PERF.md): the level-batched Subs expansion tree, the int8-matmul
// initial-dimension scan, and the batched hypercube folds.  Nothing here re-implements a stage; this
// file is assembly plus the three layout conversions between them (docs/pir/PIR65536_DEMO.md §8.4).
//
//   client (offline, gen_query65536.py) : secret key + Galois keys — INDEX-INDEPENDENT, loaded once
//   client (this file, reference/pir/client/pir_client.hpp) : the per-index query, in ~0.15 s so it can be typed
//   server (offline, encode_db.cpp)     : db65536.pir / db65536.fold, load-and-go
//   server (this file, on device)       : expand 1 ct -> 512 selectors -> scan 65 536 rows -> 7 folds
//   client (this file, on host)         : decrypt with s, round by Delta, ASCII-decode, print
//
// The assertion is the point of the whole thing: every row of db65536.txt starts with its own 5-digit
// index, so a decoded answer whose leading digits equal the requested index cannot be an accident of a
// self-consistent-but-wrong convention — the failure mode that has produced four silent bugs here.
//
//   ./pir_demo65536                          # one query, from the reference query file
//   ./pir_demo65536 -i                       # INTERACTIVE: type a row index, get the row
//   ./pir_demo65536 --idx 12345              # one query at an index, generated by the C++ client
//   ./pir_demo65536 --checks                 # add the per-stage isolation checks (slow, needs db65536.pir)
//   ./pir_demo65536 --batch 16               # THROUGHPUT: 16 queries share one scan (2 cols each of 32)
//   ./pir_demo65536 --batch 3,777,40000      # ...or an explicit list
//   ./pir_demo65536 --stream                 # do NOT hold the 6 GB database on device
//   options: --query FILE --fold FILE --txt FILE --pir FILE

