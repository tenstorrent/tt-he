using i128 = __int128;
using clk = std::chrono::steady_clock;
double ms_since(clk::time_point t) { return std::chrono::duration<double, std::milli>(clk::now() - t).count(); }

// ---- client-side arithmetic over the composite modulus q = q0*q1*q2 (~84 bit) --------------------
// The device works per RNS channel; the client has to see whole coefficients, so Garner-lift the three
// residues into a u128 and decrypt there.  s is ternary, so the negacyclic c1*s is adds and subs only:
// 2048 terms each < q < 2^83 stay far inside i128, and one reduction at the end suffices.
struct Crt {
    std::vector<uint64_t> p; u128 q, delta; uint32_t t; uint64_t i01, i012;
    Crt(const std::vector<uint32_t>& pr, uint32_t t_) : t(t_) {
        for (auto v : pr) p.push_back(v);
        q = 1; for (auto v : p) q *= v;
        delta = q / t;                                        // BFV scaling, matches onionpir_ref
        i01  = mont::modular_inverse(p[0] % p[1], p[1]);
        i012 = mont::modular_inverse((uint64_t)((u128)p[0] * p[1] % p[2]), p[2]); }
    u128 lift(uint32_t r0, uint32_t r1, uint32_t r2) const {
        uint64_t t1 = (uint64_t)((u128)((r1 + p[1] - r0 % p[1]) % p[1]) * i01 % p[1]);
        u128 x = (u128)r0 + (u128)p[0] * t1;
        uint64_t t2 = (uint64_t)((u128)((r2 + p[2] - (uint64_t)(x % p[2])) % p[2]) * i012 % p[2]);
        return x + (u128)p[0] * p[1] * t2; }
};

// ct is 2*K polys [comp*K+ch] in natural coefficient order; returns the plaintext mod t
std::vector<uint32_t> decrypt(const Crt& C, const std::vector<std::vector<uint32_t>>& ct, uint32_t K,
                              const std::vector<int32_t>& s) {
    std::vector<i128> ph(N);
    std::vector<u128> c1(N);
    for (uint32_t i = 0; i < N; ++i) {
        ph[i] = (i128)C.lift(ct[0*K+0][i], ct[0*K+1][i], ct[0*K+2][i]);
        c1[i] =       C.lift(ct[1*K+0][i], ct[1*K+1][i], ct[1*K+2][i]); }
    for (uint32_t j = 0; j < N; ++j) { const int sj = s[j]; if (!sj) continue;
        for (uint32_t i = 0; i < N; ++i) { const i128 v = (i128)c1[i] * sj; const uint32_t k = i + j;
            if (k < N) ph[k] += v; else ph[k - N] -= v; } }              // x^N = -1
    const i128 q = (i128)C.q, half = q / 2, d = (i128)C.delta;
    std::vector<uint32_t> m(N);
    for (uint32_t i = 0; i < N; ++i) {
        i128 v = ph[i] % q; if (v < 0) v += q; if (v > half) v -= q;     // centered phase = Delta*m + e
        const bool neg = v < 0; const i128 a = neg ? -v : v;
        int64_t r = (int64_t)((a + d / 2) / d);                          // round(v/Delta)
        if (neg) r = -r;
        m[i] = (uint32_t)(((r % (int64_t)C.t) + (int64_t)C.t) % (int64_t)C.t); }
    return m;
}

// plaintext coefficients -> the row string (one ASCII character per coefficient, 0 terminates)
std::string decode(const std::vector<uint32_t>& m) {
    std::string s;
    for (uint32_t i = 0; i < N; ++i) { if (m[i] == 0) break;
        s.push_back(m[i] < 128 ? (char)m[i] : '?'); }
    return s;
}
